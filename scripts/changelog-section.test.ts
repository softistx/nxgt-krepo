// Pins what the release job relies on: a section that is found comes back as the notes, and one that
// is missing comes back as `null` (exit 1 on the command line) rather than as an empty release body.

import { describe, expect, test } from "bun:test";
import { section } from "./changelog-section.ts";

const FOOTER = "<!-- generated by changesets -->\nfooter text";

const changelog = [
    "# stx-jpa",
    "",
    "## 0.3.0",
    "",
    "### Minor Changes",
    "",
    "- add queue groups",
    "",
    "## 0.2.2",
    "",
    "### Patch Changes",
    "",
    "- fix a leak",
    "",
    "## 0.2.2-beta.1",
    "",
    "- a prerelease",
    "",
    FOOTER,
].join("\n");

describe("section", () => {
    test("returns the body of the version without its heading, trimmed", () => {
        expect(section(changelog, "0.2.2")).toBe("### Patch Changes\n\n- fix a leak");
    });

    test("stops at the next version heading", () => {
        const body = section(changelog, "0.3.0");
        expect(body).toContain("add queue groups");
        expect(body).not.toContain("fix a leak");
    });

    test("the newest section does not take the footer with it", () => {
        const body = section("## 1.0.0\n\n- first\n\n" + FOOTER, "1.0.0");
        expect(body).toBe("- first");
    });

    test("a version that was never written is null, not an empty string", () => {
        expect(section(changelog, "9.9.9")).toBeNull();
    });

    test("a version is matched exactly, so 0.2.2 is not its prerelease", () => {
        expect(section(changelog, "0.2.2-beta.1")).toBe("- a prerelease");
        expect(section(changelog, "0.2")).toBeNull();
    });

    test("a section with no body is an empty string, which is not null", () => {
        expect(section("## 1.0.0\n## 0.9.0\n\n- x", "1.0.0")).toBe("");
    });

    test("a heading with trailing whitespace still matches", () => {
        expect(section("## 1.0.0  \n\n- x\n", "1.0.0")).toBe("- x");
    });

    test("a deeper heading is not a version heading", () => {
        expect(section("### 1.0.0\n\n- x\n", "1.0.0")).toBeNull();
    });
});
